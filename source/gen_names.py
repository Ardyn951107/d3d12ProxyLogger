#!/usr/bin/env python3
"""Generate names_gen.h (enum value -> name tables, GUID name table) from the
Microsoft DirectX-Headers so the logger can print readable names.

usage: gen_names.py <DirectX-Headers/include/directx> <out names_gen.h>
"""
import re, sys, os

inc, out = sys.argv[1], sys.argv[2]

def read(name):
    with open(os.path.join(inc, name), encoding="utf-8", errors="replace") as f:
        return f.read()

def enum_values(text, enum_name):
    m = re.search(r"typedef\s+enum\s+" + re.escape(enum_name) + r"\s*\{(.*?)\}\s*" + re.escape(enum_name) + r"\s*;", text, re.S)
    if not m:
        raise SystemExit("enum not found: " + enum_name)
    body = re.sub(r"//.*", "", m.group(1))
    vals, prev = {}, -1
    items = []
    for part in body.split(","):
        part = part.strip()
        if not part:
            continue
        mm = re.match(r"([A-Za-z_][A-Za-z0-9_]*)\s*(?:=\s*(.+))?$", part, re.S)
        if not mm:
            continue
        name, expr = mm.group(1), mm.group(2)
        if expr is None:
            v = prev + 1
        else:
            expr = expr.strip()
            e = re.match(r"\(\s*([A-Za-z_][A-Za-z0-9_]*)\s*\+\s*(\d+)\s*\)$", expr)
            if e:
                v = vals[e.group(1)] + int(e.group(2))
            else:
                try:
                    v = int(expr.rstrip("uUlL"), 0)
                except ValueError:
                    if expr in vals:
                        v = vals[expr]
                    else:
                        continue
        vals[name] = v
        prev = v
        items.append((name, v))
    return items

d3d12 = read("d3d12.h")
sdkl = read("d3d12sdklayers.h")
dxgif = read("dxgiformat.h")

lines = ["// generated by gen_names.py - do not edit", "#pragma once", "struct EnumName { long long v; const char* n; };"]

def emit(table, items, strip):
    lines.append("static const EnumName %s[] = {" % table)
    seen = set()
    for n, v in items:
        if v in seen or n.endswith("_MAX_VALID") or n.endswith("FORCE_UINT"):
            continue
        seen.add(v)
        lines.append('  {%d, "%s"},' % (v, n[len(strip):] if n.startswith(strip) else n))
    lines.append("  {-1, 0} };")

emit("kFeatureNames", enum_values(d3d12, "D3D12_FEATURE"), "D3D12_FEATURE_")
emit("kFormatNames", enum_values(dxgif, "DXGI_FORMAT"), "DXGI_FORMAT_")
emit("kBreadcrumbOpNames", enum_values(d3d12, "D3D12_MARKER_API"), "D3D12_MARKER_API_")  # same values as D3D12_AUTO_BREADCRUMB_OP
emit("kDredAllocNames", enum_values(d3d12, "D3D12_DRED_ALLOCATION_TYPE"), "D3D12_DRED_ALLOCATION_TYPE_")
emit("kSubobjNames", enum_values(d3d12, "D3D12_PIPELINE_STATE_SUBOBJECT_TYPE"), "D3D12_PIPELINE_STATE_SUBOBJECT_TYPE_")

# GUIDs defined with DEFINE_GUID in d3d12.h / d3d12sdklayers.h
guids = []
for t in (d3d12, sdkl):
    for g in re.findall(r"^DEFINE_GUID\(\s*([A-Za-z_][A-Za-z0-9_]*)\s*,", t, re.M):
        if g not in guids:
            guids.append(g)
lines.append("struct GuidEntry { const GUID* g; const char* n; };")
lines.append("static const GuidEntry kGuidNames[] = {")
for g in guids:
    lines.append('  {&%s, "%s"},' % (g, g))
lines.append("  {0, 0} };")

with open(out, "w") as f:
    f.write("\n".join(lines) + "\n")
print("wrote", out, "guids:", len(guids))
